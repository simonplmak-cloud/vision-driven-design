function tokenStylesheet(tokens: Record<string, string>): string {
  const vars = Object.entries(tokens)
    .filter(([, v]) => v && v.trim().length > 0)
    .map(([k, v]) => `  ${k}: ${v};`)
    .join('\n');
  return vars.length > 0 ? `:root {\n${vars}\n}\n` : '';
}

function typographyStylesheet(fonts: string[]): string {
  const stack = [...fonts, 'sans-serif']
    .filter((f) => f && f.trim().length > 0)
    .map((f) => (/^['"]/.test(f) ? f : `"${f}"`))
    .join(', ');
  return stack.length > 0 ? `body { font-family: ${stack}; }\n` : '';
}

export function generateSite(dataset: SiteDataset, capture?: CaptureBundle): GeneratedSite {
  const css = tokenStylesheet(capture?.cssTokens ?? {}) + typographyStylesheet(capture?.fonts ?? []) + SHELL_CSS;

  const files: GeneratedSiteFile[] = [
    { path: 'index.html', content: INDEX_HTML },
    { path: 'app.js', content: APP_JS },
    { path: 'style.css', content: css },
    { path: 'data/pages.json', content: JSON.stringify(dataset, null, 2) },
    { path: 'vercel.json', content: '{\n  "cleanUrls": true\n}\n' },
  ];

  return { index: 'index.html', files };
}
